/* Заголовок вкладки.
 *
 * У ведущего в один вечер открыто четыре вкладки одного адреса: кабинет,
 * пульт, экран зала и телефонный вид для проверки. Пока все они звались
 * названием квиза, отличить их в панели задач было нельзя — а переключаться
 * между ними приходится посреди игры, на глазах у зала.
 *
 * Поэтому первым идёт роль: во вкладке видно только начало строки. Дальше —
 * код вечера (их бывает несколько подряд) и то, что происходит сейчас.
 */

import { useEffect } from 'react';

export function useTitle(...parts: (string | number | null | undefined | false)[]): void {
  const text = parts.filter(Boolean).join(' · ');
  useEffect(() => {
    document.title = text || 'livequiz';
  }, [text]);
}
